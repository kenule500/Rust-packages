#!/usr/bin/env node
'use strict';

// Generates the crate index and the provider matrix from the source of truth.
//
// Run from the repository root:
//
//   node scripts/docs-matrix.js            # write docs/src/crates.md and docs/src/provider-matrix.md
//   node scripts/docs-matrix.js --check    # exit 1 when either page is stale or missing
//
// Inputs: `catalogue/00_provider_index.md` (the provider table), the package
// header of each `catalogue/NN_*.md`, and every `crates/*/Cargo.toml` plus
// `crates/wirekit/src/lib.rs`. The output is deterministic — stable ordering and
// no timestamps — so the drift check is stable across machines (NFR-002).
//
// Nothing here is hand-written status: a provider is "implemented" only when the
// Cargo feature is declared, its module source exists, and `lib.rs` wires it. A
// page therefore cannot claim a module the source does not contain (FR-007).

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CATALOGUE = path.join(ROOT, 'catalogue');
const CRATES = path.join(ROOT, 'crates');
const DOCS_SRC = path.join(ROOT, 'docs', 'src');

const PROVIDER_INDEX = '00_provider_index.md';

// Links into the repository are absolute, because a relative link that leaves
// docs/src is a broken link as far as the site is concerned (EC-004).
const REPO_BRANCH = 'main';

const BANNER = '<!-- Generated by scripts/docs-matrix.js. Do not edit by hand. -->';

const PROVIDER_STATUS = {
  implemented: 'implemented',
  featureOnly: 'feature declared, no module',
  documentedOnly: 'documented only',
};

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

// A checkout may hand us CRLF: `core.autocrlf=true` is the normal setting on
// Windows and on GitHub's windows-latest runner. This script always emits LF, so
// comparing raw bytes would report every generated page stale on such a clone
// even though the content is identical (R1-1). Line endings are not content.
function normaliseNewlines(text) {
  return text.replace(/\r\n/g, '\n');
}

function byName(a, b) {
  if (a.name < b.name) return -1;
  if (a.name > b.name) return 1;
  return 0;
}

function unquote(value) {
  const text = value.trim();
  const quoted = text.match(/^"((?:[^"\\]|\\.)*)"/);
  return quoted ? quoted[1] : text;
}

function balanced(value) {
  let depth = 0;
  for (const character of value) {
    if (character === '[') depth += 1;
    if (character === ']') depth -= 1;
  }
  return depth <= 0;
}

// A Markdown table cell cannot contain a raw pipe, and a stray newline ends the
// row. Generated values come from manifests and catalogue prose, so both are
// neutralised rather than trusted.
function cell(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();
}

// The repository URL is read from the root manifest so the site never hardcodes
// a URL that `Cargo.toml` owns.
function repositoryUrl() {
  const text = read(path.join(ROOT, 'Cargo.toml'));
  const match = text.match(/^repository\s*=\s*"([^"]+)"/m);
  if (!match) {
    throw new Error('Cargo.toml has no repository URL under [workspace.package]');
  }
  return match[1].replace(/\/+$/, '');
}

function blobUrl(repository, relativePath) {
  return `${repository}/blob/${REPO_BRANCH}/${relativePath}`;
}

function treeUrl(repository, relativePath) {
  return `${repository}/tree/${REPO_BRANCH}/${relativePath}`;
}

// A deliberately small TOML reader: only the keys this page reports are
// extracted, so no TOML dependency enters the repository for documentation.
function parseManifest(text) {
  const manifest = {
    name: null,
    version: null,
    description: null,
    published: true,
    defaultFeatures: [],
    features: [],
  };

  const lines = text.split(/\r?\n/);
  let section = '';

  for (let index = 0; index < lines.length; index += 1) {
    const trimmed = lines[index].trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const header = trimmed.match(/^\[([^\]]+)\]$/);
    if (header) {
      section = header[1].trim();
      continue;
    }

    const entry = trimmed.match(/^([A-Za-z0-9_-]+)\s*=\s*(.*)$/);
    if (!entry) continue;

    const key = entry[1];
    let value = entry[2];
    while (value.startsWith('[') && !balanced(value) && index + 1 < lines.length) {
      index += 1;
      value += ` ${lines[index].trim()}`;
    }

    if (section === 'package') {
      if (key === 'name') manifest.name = unquote(value);
      else if (key === 'version') manifest.version = unquote(value);
      else if (key === 'description') manifest.description = unquote(value);
      else if (key === 'publish') manifest.published = value.trim() !== 'false';
    } else if (section === 'features') {
      const enables = Array.from(value.matchAll(/"([^"]*)"/g), (match) => match[1]);
      manifest.features.push(key);
      if (key === 'default') manifest.defaultFeatures = enables;
    }
  }

  manifest.features.sort();
  return manifest;
}

function workspaceCrates() {
  const crates = [];

  for (const entry of fs.readdirSync(CRATES, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const manifestPath = path.join(CRATES, entry.name, 'Cargo.toml');
    if (!fs.existsSync(manifestPath)) continue;

    const manifest = parseManifest(read(manifestPath));
    if (!manifest.name) {
      throw new Error(`${manifestPath} declares no [package] name`);
    }
    crates.push({ ...manifest, dir: entry.name });
  }

  crates.sort(byName);
  return crates;
}

// Catalogue files mark their package with `**Package:** \`name\` (standalone
// crate)`. Provider design files use the same key for a module instead, so the
// suffix is what distinguishes a package from a provider.
function cataloguePackages() {
  const packages = [];

  for (const file of fs.readdirSync(CATALOGUE).sort()) {
    if (!file.endsWith('.md')) continue;

    const text = read(path.join(CATALOGUE, file));
    const header = text.match(/\*\*Package:\*\*\s*`([^`]+)`\s*\(standalone crate\)/);
    if (!header) continue;

    const status = text.match(/\*\*Status:\*\*\s*(.+)/);
    const type = text.match(/\*\*Crate type:\*\*\s*(.+)/);

    packages.push({
      name: header[1],
      file,
      status: status ? status[1].trim() : 'unknown',
      type: type ? type[1].trim() : 'unknown',
    });
  }

  packages.sort(byName);
  return packages;
}

function providerRows() {
  const file = path.join(CATALOGUE, PROVIDER_INDEX);
  const lines = read(file).split(/\r?\n/);
  const header = lines.findIndex((line) => /^\|\s*File\s*\|\s*Provider\s*\|/.test(line));
  if (header === -1) {
    throw new Error(`${PROVIDER_INDEX} has no "File | Provider | Module" table`);
  }

  const rows = [];

  for (let index = header + 1; index < lines.length; index += 1) {
    const line = lines[index].trim();
    if (!line.startsWith('|')) break;
    if (/^\|[\s:|-]+\|$/.test(line)) continue;

    const cells = line
      .split('|')
      .slice(1, -1)
      .map((value) => value.trim());
    if (cells.length < 5) continue;

    const docMatch = cells[0].match(/\[([^\]]+)\]\(([^)]+)\)/);
    const moduleMatch = cells[2].match(/`([^`]+)`/);
    if (!docMatch || !moduleMatch) {
      throw new Error(`${PROVIDER_INDEX} has an unreadable provider row: ${line}`);
    }

    const qualified = moduleMatch[1].split('::');
    const crateName = qualified[0];
    const module = qualified[1];
    if (!module) {
      throw new Error(`${PROVIDER_INDEX} names a provider without a module: ${line}`);
    }

    rows.push({
      doc: docMatch[1],
      provider: cells[1],
      qualified: moduleMatch[1],
      crateName,
      module,
      feature: module.replace(/_/g, '-'),
      api: cells[3],
      access: cells[4],
    });
  }

  if (rows.length === 0) {
    throw new Error(`${PROVIDER_INDEX} lists no providers`);
  }

  return rows;
}

function providerStatus(provider, crates) {
  const crate = crates.find((candidate) => candidate.name === provider.crateName);
  const sourceFile = crate ? path.join(CRATES, crate.dir, 'src', `${provider.module}.rs`) : null;
  const libFile = crate ? path.join(CRATES, crate.dir, 'src', 'lib.rs') : null;

  const hasFeature = Boolean(crate && crate.features.includes(provider.feature));
  const hasSource = Boolean(sourceFile && fs.existsSync(sourceFile));
  const wired = Boolean(
    crate &&
      hasFeature &&
      libFile &&
      fs.existsSync(libFile) &&
      new RegExp(
        `#\\[cfg\\(feature\\s*=\\s*"${provider.feature.replace(/[-]/g, '\\-')}"\\)\\][\\s\\S]{0,80}?pub mod ${provider.module};`
      ).test(read(libFile))
  );

  if (hasFeature && hasSource && wired) {
    return { state: PROVIDER_STATUS.implemented, crate, hasFeature, hasSource, wired };
  }
  if (hasFeature) {
    return { state: PROVIDER_STATUS.featureOnly, crate, hasFeature, hasSource, wired };
  }
  return { state: PROVIDER_STATUS.documentedOnly, crate, hasFeature, hasSource, wired };
}

function renderCrates(repository, crates, packages) {
  const lines = [];

  lines.push(BANNER);
  lines.push('');
  lines.push('# Crates');
  lines.push('');
  lines.push('This page is generated from `crates/*/Cargo.toml` and the package');
  lines.push('headers in `catalogue/`, so it reports what the workspace contains rather');
  lines.push('than what a hand-written table remembers. Regenerate it with');
  lines.push('`node scripts/docs-matrix.js`; `node scripts/docs-check.js` fails when it');
  lines.push('is stale.');
  lines.push('');
  lines.push('## Workspace members');
  lines.push('');
  lines.push('| Crate | Version | Publish | Default features | Other features | Description |');
  lines.push('|---|---|---|---|---|---|');

  for (const crate of crates) {
    const link = `[\`${crate.name}\`](${treeUrl(repository, `crates/${crate.dir}`)})`;
    const defaults =
      crate.defaultFeatures.length === 0
        ? '—'
        : crate.defaultFeatures.map((name) => `\`${name}\``).join(', ');
    // A feature that is on by default is already reported in the previous
    // column; listing it again as optional would misstate the build.
    const optional = crate.features.filter(
      (name) => name !== 'default' && !crate.defaultFeatures.includes(name)
    );

    lines.push(
      `| ${link} | ${cell(crate.version || 'unset')} | ${
        crate.published ? 'crates.io' : 'not published'
      } | ${cell(defaults)} | ${
        optional.length === 0 ? '—' : optional.map((name) => `\`${name}\``).join(', ')
      } | ${cell(crate.description || '—')} |`
    );
  }

  const workspaceNames = new Set(crates.map((crate) => crate.name));
  const pending = packages.filter((entry) => !workspaceNames.has(entry.name));

  lines.push('');
  lines.push('## Catalogue packages with no crate yet');
  lines.push('');
  lines.push('These packages have a design note in `catalogue/` but no crate in');
  lines.push('`crates/`. The status column quotes the design note; the crate status above');
  lines.push('is the one that decides what you can depend on (EC-002).');
  lines.push('');

  if (pending.length === 0) {
    lines.push('None: every catalogued package has a crate.');
  } else {
    lines.push('| Package | Catalogue status | Crate type | Design note |');
    lines.push('|---|---|---|---|');
    for (const entry of pending) {
      lines.push(
        `| \`${entry.name}\` | ${cell(entry.status)} | ${cell(entry.type)} | [\`catalogue/${entry.file}\`](${blobUrl(
          repository,
          `catalogue/${entry.file}`
        )}) |`
      );
    }
  }

  lines.push('');
  lines.push('## Provider modules');
  lines.push('');
  lines.push('Provider clients are not crates: they are feature-flagged modules of');
  lines.push('`wirekit` (CON-104). The [provider matrix](provider-matrix.md) reports which');
  lines.push('of them the source actually contains.');
  lines.push('');

  return `${lines.join('\n')}`;
}

function renderProviderMatrix(repository, crates) {
  const providers = providerRows();
  const evaluated = providers.map((provider) => ({
    ...provider,
    status: providerStatus(provider, crates),
  }));
  const implemented = evaluated.filter(
    (provider) => provider.status.state === PROVIDER_STATUS.implemented
  );

  const lines = [];

  lines.push(BANNER);
  lines.push('');
  lines.push('# Provider matrix');
  lines.push('');
  lines.push('Every provider below is a **module inside `wirekit`**, not a separate crate');
  lines.push('(CON-104). The status is read from `crates/wirekit/Cargo.toml`,');
  lines.push('`crates/wirekit/src/`, and `crates/wirekit/src/lib.rs`, so this page cannot');
  lines.push('claim a module the source does not contain (FR-007). Regenerate it with');
  lines.push('`node scripts/docs-matrix.js`.');
  lines.push('');
  lines.push(
    `${implemented.length} of ${evaluated.length} providers are implemented. A`
  );
  lines.push('provider counts as **implemented** only when all three hold: the Cargo');
  lines.push('feature is declared, the module source file exists, and `lib.rs` declares');
  lines.push('the module behind that feature.');
  lines.push('');
  lines.push('| Provider | Module | Third-party API | Access | Feature | Module source | Status |');
  lines.push('|---|---|---|---|---|---|---|');

  for (const provider of evaluated) {
    const doc = `[${cell(provider.provider)}](${blobUrl(repository, `catalogue/${provider.doc}`)})`;
    const status = provider.status;
    const source =
      status.crate && status.hasSource
        ? `[\`src/${provider.module}.rs\`](${blobUrl(
            repository,
            `crates/${status.crate.dir}/src/${provider.module}.rs`
          )})`
        : '—';
    const feature = status.hasFeature ? `\`${provider.feature}\`` : `\`${provider.feature}\` (missing)`;

    lines.push(
      `| ${doc} | \`${provider.qualified}\` | ${cell(provider.api)} | ${cell(
        provider.access
      )} | ${feature} | ${source} | ${status.state} |`
    );
  }

  const byState = new Map();
  for (const provider of evaluated) {
    const bucket = byState.get(provider.status.state) || [];
    bucket.push(`\`wirekit::${provider.module}\``);
    byState.set(provider.status.state, bucket);
  }

  lines.push('');
  lines.push('## Status legend');
  lines.push('');
  lines.push('| Status | Meaning | Providers |');
  lines.push('|---|---|---|');
  lines.push(`| implemented | Feature declared, module source present, module wired in \`lib.rs\`. | ${
    (byState.get(PROVIDER_STATUS.implemented) || []).join(', ') || '—'
  } |`);
  lines.push(`| feature declared, no module | The Cargo feature exists but enables nothing. | ${
    (byState.get(PROVIDER_STATUS.featureOnly) || []).join(', ') || '—'
  } |`);
  lines.push(`| documented only | A design note exists; no feature and no module. | ${
    (byState.get(PROVIDER_STATUS.documentedOnly) || []).join(', ') || '—'
  } |`);
  lines.push('');
  lines.push('Each provider needs its own feature for its own module, and enabling one');
  lines.push('feature never enables another (CON-204). The catalogue note is the design');
  lines.push('contract for a provider; the status column is what the code ships.');
  lines.push('');
  lines.push('```toml');
  lines.push('[dependencies]');
  lines.push(
    `wirekit = { version = "${(crates.find((crate) => crate.name === 'wirekit') || {}).version || '0.1'}", features = ["twilio", "sendgrid"] }`
  );
  lines.push('```');
  lines.push('');

  return `${lines.join('\n')}`;
}

function main(argv) {
  const check = argv.includes('--check');
  const repository = repositoryUrl();
  const crates = workspaceCrates();
  const packages = cataloguePackages();

  if (!fs.existsSync(DOCS_SRC)) {
    throw new Error('docs/src is missing; the mdBook scaffold has not been created');
  }

  const outputs = [
    { file: path.join(DOCS_SRC, 'crates.md'), content: renderCrates(repository, crates, packages) },
    {
      file: path.join(DOCS_SRC, 'provider-matrix.md'),
      content: renderProviderMatrix(repository, crates),
    },
  ];

  let failures = 0;

  for (const output of outputs) {
    const relative = path.relative(ROOT, output.file).split(path.sep).join('/');
    const current = fs.existsSync(output.file) ? read(output.file) : null;

    if (check) {
      if (current === null) {
        console.error(`${relative} is missing — run: node scripts/docs-matrix.js`);
        failures += 1;
      } else if (normaliseNewlines(current) !== output.content) {
        console.error(`${relative} is stale — run: node scripts/docs-matrix.js`);
        failures += 1;
      }
    } else if (normaliseNewlines(current) !== output.content) {
      fs.writeFileSync(output.file, output.content, 'utf8');
      console.log(`wrote ${relative}`);
    }
  }

  if (check && failures === 0) {
    console.log(`docs-matrix: ${outputs.length} generated page(s) up to date`);
  }

  return failures === 0 ? 0 : 1;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`docs-matrix: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { main, parseManifest };
