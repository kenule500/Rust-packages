#!/usr/bin/env node
'use strict';

// Generates the stable error-code reference from the crates' source.
//
// Run from the repository root:
//
//   node scripts/docs-errors.js            # write docs/src/errors.md
//   node scripts/docs-errors.js --check    # exit 1 when the page is stale or missing
//
// Nothing on the page is typed by hand (FR-003, AC-005). Four shapes are read
// out of `crates/*/src/**/*.rs`:
//
//   pub const CODE_X: &str = "W2004";      doc comment above the constant
//   #[error("QL-EXCEEDED: ...")]           the Display template
//   Self::Variant => "PC-AUTH",            the doc comment on the enum variant
//   .error("D1003", "anchors ...")         the message literal at the call site
//
// Each file is scanned only up to its first `#[cfg(test)]` module, so a code
// exercised in a unit test is not presented as an additional definition. The
// output is deterministic: crates in name order, codes in code order, first
// definition win, no timestamps (NFR-002).

const fs = require('fs');
const path = require('path');

const { parseManifest } = require('./docs-matrix.js');

const ROOT = path.resolve(__dirname, '..');
const CRATES = path.join(ROOT, 'crates');
const DOCS_SRC = path.join(ROOT, 'docs', 'src');
const OUTPUT = path.join(DOCS_SRC, 'errors.md');

const REPO_BRANCH = 'main';
const BANNER = '<!-- Generated by scripts/docs-errors.js. Do not edit by hand. -->';

// A stable code is uppercase, may carry `-` or `_` segments, and is not a plain
// word: `W2004`, `D1010`, `QL-EXCEEDED`, `PC-RATE-LIMIT`,
// `LOCALSERVICES_ACCOUNT_NOT_APPROVED`. The digit/separator requirement keeps
// unrelated match arms such as `"GET"` out of the reference.
const CODE_SHAPE = /^[A-Z][A-Z0-9]*(?:[_-][A-Z0-9]+)*$/;
const isCode = (value) => CODE_SHAPE.test(value) && /[0-9_-]/.test(value);

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

function compareText(a, b) {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

function repositoryUrl() {
  const text = read(path.join(ROOT, 'Cargo.toml'));
  const match = text.match(/^repository\s*=\s*"([^"]+)"/m);
  if (!match) {
    throw new Error('Cargo.toml has no repository URL under [workspace.package]');
  }
  return match[1].replace(/\/+$/, '');
}

function workspaceCrates() {
  const crates = [];

  for (const entry of fs.readdirSync(CRATES, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const manifestPath = path.join(CRATES, entry.name, 'Cargo.toml');
    if (!fs.existsSync(manifestPath)) continue;

    const manifest = parseManifest(read(manifestPath));
    if (!manifest.name) throw new Error(`${manifestPath} declares no [package] name`);
    crates.push({ name: manifest.name, dir: entry.name });
  }

  crates.sort((a, b) => compareText(a.name, b.name));
  return crates;
}

function rustFiles(dir) {
  const files = [];
  const pending = [dir];

  while (pending.length > 0) {
    const current = pending.pop();
    const entries = fs
      .readdirSync(current, { withFileTypes: true })
      .sort((a, b) => compareText(a.name, b.name));

    for (const entry of entries) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) pending.push(full);
      else if (entry.name.endsWith('.rs')) files.push(full);
    }
  }

  files.sort(compareText);
  return files;
}

// Unit tests live in an inline `#[cfg(test)]` module (CON-403). Everything after
// the first one is test code, so the scan stops there.
function liveLines(text) {
  const lines = text.split(/\r?\n/);
  const end = lines.findIndex((line) => /^\s*#\[cfg\(test\)\]\s*$/.test(line));
  return end === -1 ? lines : lines.slice(0, end);
}

function docText(line) {
  return line.trim().replace(/^\/\/\/\s?/, '').trim();
}

// Resolves `Self::Variant => "CODE"` to the doc comment on the variant itself.
function variantDocs(lines) {
  const docs = new Map();

  for (let index = 0; index < lines.length; index += 1) {
    const variant = lines[index].match(/^\s{4}([A-Za-z0-9_]+)(?:\s*\{|\s*\(|,)\s*$/);
    if (!variant) continue;

    const collected = [];
    for (let back = index - 1; back >= 0; back -= 1) {
      const trimmed = lines[back].trim();
      if (trimmed.startsWith('///')) {
        collected.unshift(docText(trimmed));
        continue;
      }
      if (trimmed.startsWith('//') || trimmed === '') break;
      break;
    }

    if (collected.length > 0 && !docs.has(variant[1])) {
      docs.set(variant[1], collected.join(' '));
    }
  }

  return docs;
}

function scanFile(text) {
  const lines = liveLines(text);
  const docs = variantDocs(lines);
  const entries = [];
  let doc = [];

  for (const line of lines) {
    const trimmed = line.trim();

    if (trimmed.startsWith('///')) {
      doc.push(docText(trimmed));
      continue;
    }

    const constant = trimmed.match(/^pub const [A-Z0-9_]+: &str = "([^"]+)";$/);
    if (constant && isCode(constant[1])) {
      entries.push({
        code: constant[1],
        kind: doc.length > 0 ? 'doc' : 'none',
        meaning: doc.join(' '),
      });
      doc = [];
      continue;
    }

    const attribute = trimmed.match(/^#\[error\("(.+)"\)\]$/);
    if (attribute) {
      const rendered = attribute[1];
      const separated = rendered.match(/^([A-Z][A-Z0-9]*(?:[_-][A-Z0-9]+)*):\s*(.+)$/);
      const spaced = rendered.match(/^([A-Z][0-9]{4})\s+(.+)$/);
      const match = separated || spaced;

      if (match && isCode(match[1])) {
        // `#[error("QL-BACKEND: {0}")]` renders a caller-supplied message, so the
        // template alone says nothing. The variant's own doc comment does.
        const placeholder = /^\{[^}]*\}/.test(match[2]);
        entries.push({
          code: match[1],
          kind: placeholder && doc.length > 0 ? 'doc' : 'message',
          meaning: placeholder && doc.length > 0 ? doc.join(' ') : match[2],
        });
      }
      doc = [];
      continue;
    }

    const arm = trimmed.match(/^Self::([A-Za-z0-9_]+)\s*=>\s*"([^"]+)",$/);
    if (arm && isCode(arm[2])) {
      const meaning = docs.get(arm[1]);
      entries.push({
        code: arm[2],
        kind: meaning ? 'doc' : 'none',
        meaning: meaning || '',
      });
      doc = [];
      continue;
    }

    for (const call of line.matchAll(/\.error\("([^"]+)",\s*"([^"]*)"\)/g)) {
      if (isCode(call[1])) {
        entries.push({ code: call[1], kind: 'message', meaning: call[2] });
      }
    }

    doc = [];
  }

  return entries;
}

function collect(repository, crates) {
  const collected = new Map();

  for (const crate of crates) {
    const sourceDir = path.join(CRATES, crate.dir, 'src');
    if (!fs.existsSync(sourceDir)) continue;

    const codes = new Map();

    for (const file of rustFiles(sourceDir)) {
      const relative = path
        .relative(path.join(ROOT, 'crates', crate.dir), file)
        .split(path.sep)
        .join('/');

      for (const entry of scanFile(read(file))) {
        const existing = codes.get(entry.code);
        if (!existing) {
          codes.set(entry.code, {
            code: entry.code,
            docMeaning: entry.kind === 'doc' ? entry.meaning : null,
            messages: entry.kind === 'message' && entry.meaning ? [entry.meaning] : [],
            where: `crates/${crate.dir}/${relative}`,
          });
          continue;
        }

        if (entry.kind === 'doc' && !existing.docMeaning && entry.meaning) {
          existing.docMeaning = entry.meaning;
        } else if (entry.kind === 'message' && entry.meaning) {
          if (!existing.messages.includes(entry.meaning)) existing.messages.push(entry.meaning);
        }
      }
    }

    collected.set(crate.name, codes);
  }

  return collected;
}

function meaningOf(entry) {
  if (entry.docMeaning) return entry.docMeaning;
  if (entry.messages.length > 0) return entry.messages.join('; ');
  return '—';
}

function render(repository, crates, collected) {
  const lines = [];

  lines.push(BANNER);
  lines.push('');
  lines.push('# Error codes');
  lines.push('');
  lines.push('Every code below was read from the crates\' source, not typed by hand');
  lines.push('(FR-003, AC-005). A published code keeps its meaning for the life of the');
  lines.push('crate and is never reused for a different failure (CON-205); the upgrade');
  lines.push('policy in [Upgrading](upgrading.md) explains what that means across');
  lines.push('versions.');
  lines.push('');
  lines.push('The scan reads `crates/*/src/**/*.rs` up to each file\'s first');
  lines.push('`#[cfg(test)]` module, and collects four shapes:');
  lines.push('');
  lines.push('- `pub const CODE_X: &str = "W2004";` — meaning from the doc comment above');
  lines.push('  the constant.');
  lines.push('- `#[error("QL-EXCEEDED: ...")]` — meaning from the rendered message.');
  lines.push('- `Self::Variant => "PC-AUTH",` — meaning from the doc comment on the enum');
  lines.push('  variant.');
  lines.push('- `.error("D1003", "anchors are not supported")` — meaning from the message');
  lines.push('  literal at the call site.');
  lines.push('');
  lines.push('Where one code is raised from several places, every distinct message is');
  lines.push('listed, in source order. Regenerate with `node scripts/docs-errors.js`;');
  lines.push('`node scripts/docs-check.js` fails when this page is stale.');
  lines.push('');

  let documented = 0;
  const silent = [];

  for (const crate of crates) {
    const codes = collected.get(crate.name) || new Map();
    if (codes.size === 0) {
      silent.push(crate);
      continue;
    }

    documented += codes.size;
    const sorted = Array.from(codes.values()).sort((a, b) => compareText(a.code, b.code));

    lines.push(`## \`${crate.name}\``);
    lines.push('');
    lines.push('| Code | Meaning | Source |');
    lines.push('|---|---|---|');
    for (const entry of sorted) {
      const meaning = meaningOf(entry).replace(/\|/g, '\\|').trim();
      lines.push(
        `| \`${entry.code}\` | ${meaning} | [\`${entry.where.split('/').slice(2).join('/')}\`](${repository}/blob/${REPO_BRANCH}/${entry.where}) |`
      );
    }
    lines.push('');
  }

  lines.push('## Crates with no stable codes');
  lines.push('');
  if (silent.length === 0) {
    lines.push('None: every crate declares at least one stable code.');
  } else {
    lines.push('These crates declare no stable error code in their `src/`:');
    lines.push('');
    for (const crate of silent) {
      lines.push(`- \`${crate.name}\``);
    }
  }
  lines.push('');
  lines.push(
    `Total: ${documented} stable codes across ${crates.length - silent.length} crate(s).`
  );
  lines.push('');

  return lines.join('\n');
}

function main(argv) {
  const check = argv.includes('--check');
  const repository = repositoryUrl();
  const crates = workspaceCrates();

  if (!fs.existsSync(DOCS_SRC)) {
    throw new Error('docs/src is missing; the mdBook scaffold has not been created');
  }

  const content = render(repository, crates, collect(repository, crates));
  const relative = path.relative(ROOT, OUTPUT).split(path.sep).join('/');
  const current = fs.existsSync(OUTPUT) ? read(OUTPUT) : null;

  if (check) {
    if (current === null) {
      console.error(`${relative} is missing — run: node scripts/docs-errors.js`);
      return 1;
    }
    if (current !== content) {
      console.error(`${relative} is stale — run: node scripts/docs-errors.js`);
      return 1;
    }
    console.log('docs-errors: generated page up to date');
    return 0;
  }

  if (current !== content) {
    fs.writeFileSync(OUTPUT, content, 'utf8');
    console.log(`wrote ${relative}`);
  }

  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    console.error(`docs-errors: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { main, scanFile };
