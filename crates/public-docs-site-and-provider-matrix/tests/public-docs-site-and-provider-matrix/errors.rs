//! AC-005: the error-reference page lists every documented `WirekitError` code
//! and every crate's stable codes, read from source rather than typed by hand.

mod support;

use support::{assert_node_ok, crate_source_mentions, read};

#[test]
fn ac_005_error_reference_matches_the_crates_source() {
    // The page is byte-reproducible from a fresh scan of the source, which is what
    // "generated, not hand-maintained" means. A hand edit breaks this.
    assert_node_ok("scripts/docs-errors.js", &["--check"]);

    let page = read("docs/src/errors.md");
    assert!(
        page.starts_with("<!-- Generated by scripts/docs-errors.js."),
        "the error reference must declare itself generated"
    );

    // Every WirekitError code, which is the AC's explicit requirement.
    for code in [
        "W2001", "W2002", "W2003", "W2004", "W2005", "W2006", "W2007",
    ] {
        assert!(
            page.contains(&format!("`{code}`")),
            "the error reference is missing WirekitError code {code}"
        );
        assert!(
            crate_source_mentions("wirekit", code),
            "{code} is documented but not declared anywhere in crates/wirekit/src"
        );
    }

    // One stable code from each remaining crate, proven to exist in that crate's
    // source so the page cannot attribute a code to the wrong crate.
    for (crate_name, code) in [
        ("dado-yaml", "D1003"),
        ("hookgate", "HG-VERIFY-SIGNATURE"),
        ("platform-core", "PC-RATE-LIMIT"),
        ("quota-ledger", "QL-EXCEEDED"),
        ("syncforge", "SF-TRANSPORT"),
        ("wirekit", "W2004"),
    ] {
        assert!(
            page.contains(&format!("`{code}`")),
            "the error reference is missing {crate_name}'s code {code}"
        );
        assert!(
            crate_source_mentions(crate_name, code),
            "{code} is documented under {crate_name} but not declared in its source"
        );
    }

    // The page states the totals it found, so a scan that silently stops seeing a
    // crate is visible on the page rather than only in a test.
    assert!(
        page.contains("Total: ") && page.contains(" stable codes across "),
        "the error reference must report the totals it read"
    );
}
